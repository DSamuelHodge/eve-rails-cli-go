func renderPlatformChannel(name string, component *config.CatalogComponent, auth string) string {
	kind := component.Kind
	if kind == "" {
		kind = name
	}
	switch kind {
	case "eve":
		return renderEveChannel(auth)
	case "twilio":
		return renderTwilioChannel(component)
	case "slack":
		return renderSlackChannel(component)
	case "discord":
		return renderDiscordChannel()
	case "telegram":
		return renderTelegramChannel(component)
	case "linear":
		return renderLinearChannel(component)
	case "github":
		return renderGithubChannel(component)
	case "teams":
		return renderTeamsChannel()
	default:
		return renderCustomChannelPlaceholder(name)
	}
}

