	version := agent.Version
	if version == "" {
		version = "1.0.0"
	}
	fmt.Fprintf(&output, "version: %s\n", version)
	owner := agent.Owner
	if owner == "" {
		owner = manifest.Defaults.Owner
	}
	fmt.Fprintf(&output, "owner: %s\n", owner)
	model := agent.Model
	if model == "" {
		model = manifest.Defaults.Model
	}
	fmt.Fprintf(&output, "model: %s\n", model)
	fmt.Fprintf(&output, "responsibility: %q\n", agent.Responsibility)
	output.WriteString("uses:\n")
	appendComponentMap(&output, "tools", agent.Tools)
	appendComponentMap(&output, "skills", agent.Skills)
	appendComponentMap(&output, "memory", agent.Memory)
