func tsConfigValue(value string) string {
	if strings.HasPrefix(value, "env:") {
		return fmt.Sprintf("process.env.%s!", strings.TrimSpace(strings.TrimPrefix(value, "env:")))
	}
	if value == "*" {
		return "\"*\""
	}
	if strings.Contains(value, ",") {
		parts := strings.Split(value, ",")
		var items []string
		for _, item := range parts {
			items = append(items, fmt.Sprintf("\"%s\"", EscapeTSString(strings.TrimSpace(item))))
		}
		return "[" + strings.Join(items, ", ") + "]"
	}
	return fmt.Sprintf("\"%s\"", EscapeTSString(value))
}

