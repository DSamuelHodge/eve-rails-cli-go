	appendOptionalString(&output, "risk", agent.Risk)
	appendOptionalString(&output, "auth", agent.Auth)
	appendOptionalString(&output, "visibility", agent.Visibility)
	if agent.CostBudget != nil {
		fmt.Fprintf(&output, "cost_budget: %g\n", *agent.CostBudget)
	}
	if agent.TokenBudget != nil {
		fmt.Fprintf(&output, "token_budget: %d\n", *agent.TokenBudget)
	}
	appendOptionalString(&output, "timeout", agent.Timeout)
	if agent.RuntimePolicy != nil {
		appendYAMLValue(&output, "runtime_policy", agent.RuntimePolicy)
	}
	if agent.Topology != nil {
		appendYAMLValue(&output, "topology", agent.Topology)
	}
